// Toggle submenu
function toggleSubmenu(element) {
    const navItem = element.closest('.nav-item');
    navItem.classList.toggle('expanded');
}

// Toggle actions dropdown
function toggleActionsMenu(element, event) {
    event.stopPropagation();
    const dropdown = element.closest('.actions-dropdown');
    const wasOpen = dropdown.classList.contains('open');

    // Close all other dropdowns
    document.querySelectorAll('.actions-dropdown.open').forEach(d => d.classList.remove('open'));

    if (!wasOpen) {
        dropdown.classList.add('open');
    }
}

// Close dropdowns when clicking outside
document.addEventListener('click', function(event) {
    if (!event.target.closest('.actions-dropdown')) {
        document.querySelectorAll('.actions-dropdown.open').forEach(d => d.classList.remove('open'));
    }
});

// Format time ago
function timeAgo(date) {
    const seconds = Math.floor((new Date() - date) / 1000);

    let interval = seconds / 31536000;
    if (interval > 1) return Math.floor(interval) + ' 年前';

    interval = seconds / 2592000;
    if (interval > 1) return Math.floor(interval) + ' 月前';

    interval = seconds / 86400;
    if (interval > 1) return Math.floor(interval) + ' 天前';

    interval = seconds / 3600;
    if (interval > 1) return Math.floor(interval) + ' 小时前';

    interval = seconds / 60;
    if (interval > 1) return Math.floor(interval) + ' 分钟前';

    return Math.floor(seconds) + ' 秒前';
}

// Format bytes
function formatBytes(bytes, decimals = 2) {
    if (bytes === 0) return '0 Bytes';

    const k = 1024;
    const dm = decimals < 0 ? 0 : decimals;
    const sizes = ['Bytes', 'KB', 'MB', 'GB', 'TB', 'PB'];

    const i = Math.floor(Math.log(bytes) / Math.log(k));

    return parseFloat((bytes / Math.pow(k, i)).toFixed(dm)) + ' ' + sizes[i];
}

// Init page icons
function initIcons() {
    document.querySelectorAll('[data-icon]').forEach(el => {
        const iconName = el.getAttribute('data-icon');
        el.innerHTML = getIcon(iconName);
    });
}

// Run when DOM is ready
document.addEventListener('DOMContentLoaded', initIcons);
